/* ---- char_to_enum conversion ---- */
Character char_to_enum(char ch) {
    if (ch >= '0' && ch <= '9') return (Character)(CHAR_0 + (ch - '0'));
    if (ch >= 'A' && ch <= 'Z') return (Character)(CHAR_A + (ch - 'A'));
    if (ch >= 'a' && ch <= 'z') return (Character)(CHAR_A + (ch - 'a'));
    switch (ch) {
        case ':': return CHAR_COLON;
        case '-': return CHAR_DASH;
        case '%': return CHAR_PERCENTAGE;
        case '.': return CHAR_DOT;
        case ' ': return CHAR_EMPTY;
        default:  return CHAR_NONE;
    }
}

